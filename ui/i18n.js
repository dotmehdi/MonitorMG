// « Annuler » veut dire Undo dans l'activité et Cancel dans les dialogues.
const CANCEL = LANG === "en" ? "Cancel" : "Annuler";

/** Traduit un texte français ; {0}, {1}… reçoivent les arguments. */
function t(fr, ...args) {
  const s = (LANG === "en" && EN[fr]) || fr;
  return args.length ? s.replace(/\{(\d)\}/g, (_, i) => args[i]) : s;
}

// Textes de la page : nœuds texte, title et aria-label dont le contenu est une clé.
document.documentElement.lang = LANG;
if (LANG === "en") {
  document.title = t(document.title);
  const walk = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT);
  for (let n = walk.nextNode(); n; n = walk.nextNode()) {
    const k = n.data.trim();
    if (EN[k]) n.data = n.data.replace(k, EN[k]);
  }
  for (const e of document.querySelectorAll("[title], [aria-label]")) {
    for (const a of ["title", "aria-label"]) if (EN[e.getAttribute(a)]) e.setAttribute(a, EN[e.getAttribute(a)]);
  }
}
